import { expect, test } from "@playwright/test"

const admin = { Authorization: "Bearer e2e-admin-token-only-for-local-tests" }

test("user allocation, token reports, private portal, disable and revoke", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", e => errors.push(e.message))
  await page.goto("/")
  await page.getByLabel("管理员令牌").fill("e2e-admin-token-only-for-local-tests")
  await page.getByRole("button", { name: "进入控制台" }).click()
  await page.getByRole("link", { name: "用户管理", exact: true }).click()
  await page.getByRole("button", { name: "创建用户", exact: true }).click()
  await page.getByLabel("用户名称", { exact: true }).fill("产品团队")
  await page.getByLabel("备注", { exact: true }).fill("用于多用户用量验证")
  await page.getByRole("button", { name: "保存用户" }).click()
  const userRow = page.getByRole("row").filter({ hasText: "产品团队" })
  await expect(userRow).toBeVisible()
  await userRow.getByRole("link", { name: "分配 Key" }).click()
  await page.getByRole("button", { name: "创建密钥", exact: true }).first().click()
  await expect(page.getByRole("dialog").getByLabel("归属用户", { exact: true })).toContainText("产品团队")
  await page.getByLabel("密钥名称").fill("产品团队 Web")
  await page.getByRole("dialog").getByRole("button", { name: "创建密钥", exact: true }).click()
  await expect(page.getByRole("heading", { name: "API 密钥已创建" })).toBeVisible()
  const token = await page.locator(".created-key code").innerText()
  await page.getByRole("button", { name: "我已保存" }).click()

  const { data: users } = await (await page.request.get("/api/admin/users", { headers: admin })).json()
  const user = users.find((u: { name: string }) => u.name === "产品团队")
  expect(user.enabled).toBe(true)
  const second = await (await page.request.post("/api/admin/keys", { headers: admin, data: { name: "产品团队 CLI", user_id: user.id } })).json()
  const bob = await (await page.request.post("/api/admin/users", { headers: admin, data: { name: "其他团队" } })).json()
  const bobKey = await (await page.request.post("/api/admin/keys", { headers: admin, data: { name: "其他团队专用", user_id: bob.id } })).json()
  await page.request.post("/api/admin/upstreams", { headers: admin, data: { name: "Usage fixture", base_url: "http://127.0.0.1:18090/v1", region: "us-east-1", auth_mode: "api_key", api_key: "mock-bedrock-key", weight: 1, enabled: true, models: {} } })
  for (const [key, stream, model] of [[token, false, "mock-model"], [token, true, "mock-reasoning"], [second.token, false, "mock-model"], [bobKey.token, false, "other-team-model"]] as const) {
    const result = await page.request.post("/v1/chat/completions", { headers: { Authorization: `Bearer ${key}` }, data: { model, messages: [{ role: "user", content: "hello" }], stream } })
    expect(result.status()).toBe(200)
    await result.body()
  }
  const privateReport = await (await page.request.get(`/api/me/usage?all=true&user_id=${bob.id}`, { headers: { Authorization: `Bearer ${token}` } })).json()
  expect(privateReport.totals.total_tokens).toBe(60)
  expect(privateReport.totals.requests).toBe(3)
  expect(privateReport.by_user).toHaveLength(1)
  expect(privateReport.by_user[0].id).toBe(user.id)
  expect(privateReport.by_model).toHaveLength(2)
  expect((await page.request.get("/api/admin/users", { headers: { Authorization: `Bearer ${token}` } })).status()).toBe(401)

  await page.getByRole("link", { name: "用户管理", exact: true }).click()
  await page.getByRole("button", { name: "刷新数据", exact: true }).click()
  await expect(userRow.getByText("60", { exact: true })).toBeVisible()
  await page.screenshot({ path: "../test-results/users-desktop.png", fullPage: true })
  await userRow.getByRole("link", { name: "用量", exact: true }).click()
  await expect(page.getByRole("heading", { name: "用量统计", exact: true })).toBeVisible()
  await expect(page.locator(".usage-stats .stat-value").first()).toHaveText("60")
  await expect(page.getByRole("tab", { name: "按模型" })).toHaveAttribute("aria-selected", "true")
  const modelPanel = page.getByRole("region", { name: "模型用量", exact: true })
  await expect(modelPanel.getByRole("button", { name: "筛选模型 mock-model", exact: true })).toContainText("66.7%")
  await expect(modelPanel.getByRole("button", { name: "筛选模型 mock-reasoning", exact: true })).toContainText("33.3%")
  await modelPanel.getByRole("button", { name: "筛选模型 mock-model", exact: true }).click()
  await expect(page.locator(".usage-stats .stat-value").first()).toHaveText("40")
  await expect(page.locator(".usage-breakdown tbody tr")).toHaveCount(1)
  await page.getByRole("combobox", { name: "筛选模型", exact: true }).click()
  await expect(page.getByRole("option", { name: "mock-reasoning", exact: true })).toBeVisible()
  await expect(page.getByRole("option", { name: "other-team-model", exact: true })).toHaveCount(0)
  await page.getByRole("combobox", { name: "搜索筛选模型", exact: true }).fill("reasoning")
  await page.getByRole("combobox", { name: "搜索筛选模型", exact: true }).press("Enter")
  await expect(page.locator(".usage-stats .stat-value").first()).toHaveText("20")
  await expect(page.getByRole("combobox", { name: "筛选模型", exact: true })).toBeFocused()
  await page.getByRole("button", { name: "清除模型筛选" }).click()
  await expect(page.locator(".usage-stats .stat-value").first()).toHaveText("60")
  const modelDownload = page.waitForEvent("download")
  await page.getByRole("button", { name: "导出 CSV" }).click()
  expect((await modelDownload).suggestedFilename()).toMatch(/mantle-usage-by_model.*\.csv/)
  const toast = page.getByRole("button", { name: "关闭通知", exact: true })
  if (await toast.isVisible()) await toast.click()
  await page.screenshot({ path: "../test-results/usage-models-desktop.png", fullPage: true })
  await page.getByRole("tab", { name: "按密钥" }).click()
  await expect(page.getByRole("cell", { name: "产品团队 Web", exact: false })).toBeVisible()
  const download = page.waitForEvent("download")
  await page.getByRole("button", { name: "导出 CSV" }).click()
  expect((await download).suggestedFilename()).toMatch(/mantle-usage-by_key.*\.csv/)
  await page.screenshot({ path: "../test-results/usage-desktop.png", fullPage: true })
  await page.getByRole("button", { name: "退出登录", exact: true }).click()
  await page.getByRole("button", { name: "用户用量查询", exact: true }).click()
  await page.getByLabel("API Key", { exact: true }).fill(token)
  await page.getByRole("button", { name: "查看用量", exact: true }).click()
  await expect(page.getByRole("heading", { name: "我的用量", exact: true })).toBeVisible()
  await expect(page.locator(".usage-stats .stat-value").first()).toHaveText("60")
  await expect(page.getByRole("link", { name: "用户管理", exact: true })).toHaveCount(0)
  await expect(page.getByText("其他团队专用", { exact: true })).toHaveCount(0)
  await page.getByRole("combobox", { name: "筛选模型", exact: true }).click()
  await expect(page.getByRole("option", { name: "mock-reasoning", exact: true })).toBeVisible()
  await expect(page.getByRole("option", { name: "other-team-model", exact: true })).toHaveCount(0)
  await page.getByRole("combobox", { name: "搜索筛选模型", exact: true }).press("Escape")
  await page.screenshot({ path: "../test-results/user-portal-desktop.png", fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: "../test-results/user-portal-mobile.png", fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

  await page.request.put(`/api/admin/users/${user.id}`, { headers: admin, data: { name: user.name, enabled: false } })
  for (const key of [token, second.token]) {
    expect((await page.request.get("/api/me/usage", { headers: { Authorization: `Bearer ${key}` } })).status()).toBe(401)
  }
  await page.request.put(`/api/admin/users/${user.id}`, { headers: admin, data: { name: user.name, enabled: true } })
  expect((await page.request.get("/api/me", { headers: { Authorization: `Bearer ${token}` } })).status()).toBe(200)
  const allKeys = await (await page.request.get(`/api/admin/keys?user_id=${user.id}`, { headers: admin })).json()
  await page.request.delete(`/api/admin/keys/${allKeys.data.find((k: { name: string }) => k.name === "产品团队 Web").id}`, { headers: admin })
  await page.getByRole("button", { name: "刷新用量", exact: true }).click()
  await expect(page.getByRole("heading", { name: "登录管理控制台", exact: true })).toBeVisible()
  const retained = await (await page.request.get("/api/me/usage?all=true", { headers: { Authorization: `Bearer ${second.token}` } })).json()
  expect(retained.totals.total_tokens).toBe(60)
  expect(retained.by_key).toHaveLength(2)
  expect(errors).toEqual([])
})
