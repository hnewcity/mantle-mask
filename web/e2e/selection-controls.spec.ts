import { expect, test } from "@playwright/test"

test("consistent dropdowns, searchable model entry and bounded Chinese calendars", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  await page.goto("/")
  await page.getByLabel("管理员令牌").fill("e2e-admin-token-only-for-local-tests")
  await page.getByRole("button", { name: "进入控制台" }).click()
  await page.getByRole("link", { name: "用量统计", exact: true }).click()

  const start = page.getByRole("button", { name: "开始日期", exact: true })
  const end = page.getByRole("button", { name: "结束日期", exact: true })
  const firstDate = await start.innerText()
  for (const width of [1440, 811, 390, 360]) {
    await page.setViewportSize({ width, height: 889 })
    await start.click()
    const calendar = page.getByRole("dialog", { name: "选择开始日期" })
    await expect(calendar.getByRole("grid")).toBeVisible()
    const bounds = await calendar.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    await expect(calendar.getByRole("button", { name: new RegExp(`^${firstDate}`) })).toBeFocused()
    await page.screenshot({ path: `../test-results/calendar-${width}.png`, fullPage: false })
    await page.keyboard.press("Escape")
    await expect(calendar).toHaveCount(0)
    await expect(start).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

    await page.getByRole("combobox", { name: "筛选用户", exact: true }).click()
    const list = page.getByRole("listbox")
    await expect(list).toBeVisible()
    const listBounds = await list.boundingBox()
    expect(listBounds!.x + listBounds!.width).toBeLessThanOrEqual(width)
    await page.screenshot({ path: `../test-results/dropdown-${width}.png`, fullPage: false })
    await page.keyboard.press("Escape")
    await expect(page.getByRole("combobox", { name: "筛选用户", exact: true })).toBeFocused()
  }

  await page.setViewportSize({ width: 1440, height: 1060 })
  await start.click()
  await page.getByRole("dialog", { name: "选择开始日期" }).getByRole("button", { name: "今天", exact: true }).click()
  await expect(start).toHaveText(await end.innerText())
  await expect(page.getByRole("region", { name: "用量筛选" }).getByRole("button", { name: "今天", exact: true })).toHaveAttribute("aria-pressed", "true")
  await end.click()
  const endCalendar = page.getByRole("dialog", { name: "选择结束日期" })
  await expect(endCalendar.getByRole("button", { name: "上个月" })).toHaveAttribute("aria-disabled", "true")
  await expect(endCalendar.locator(".rdp-day[data-disabled] button").first()).toBeDisabled()
  await page.keyboard.press("ArrowRight")
  await page.keyboard.press("Enter")
  await expect(endCalendar).toHaveCount(0)
  expect(await end.innerText()).not.toBe(await start.innerText())
  await start.click()
  const startCalendar = page.getByRole("dialog", { name: "选择开始日期" })
  await expect(startCalendar.locator(".rdp-day[data-disabled] button").last()).toBeDisabled()
  await page.keyboard.press("Escape")
  await page.getByRole("region", { name: "用量筛选" }).getByRole("button", { name: "全部历史", exact: true }).click()
  await expect(start).toBeDisabled()
  await expect(end).toBeDisabled()
  await page.getByRole("region", { name: "用量筛选" }).getByRole("button", { name: "自定义日期" }).click()
  await expect(start).toBeEnabled()
  await page.getByRole("combobox", { name: "筛选模型", exact: true }).click()
  await page.getByRole("combobox", { name: "搜索筛选模型", exact: true }).press("Shift+Tab")
  await expect(page.getByRole("combobox", { name: "筛选上游", exact: true })).toBeFocused()
  await page.getByRole("combobox", { name: "筛选模型", exact: true }).click()
  await page.getByRole("combobox", { name: "搜索筛选模型", exact: true }).press("Tab")
  await expect(page.getByRole("combobox", { name: "筛选模型", exact: true })).not.toBeFocused()
  await expect(page.getByRole("dialog", { name: "筛选模型选项" })).toHaveCount(0)

  await page.getByRole("link", { name: "上游端点", exact: true }).click()
  await page.getByRole("button", { name: "添加上游", exact: true }).click()
  await page.getByRole("button", { name: /AWS SigV4/ }).click()
  await page.getByRole("combobox", { name: "签名服务" }).click()
  await page.getByRole("option", { name: "bedrock", exact: true }).click()
  await expect(page.getByRole("dialog", { name: "连接一个新的上游" })).toBeVisible()
  await expect(page.getByRole("combobox", { name: "签名服务" })).toHaveText("bedrock")
  await expect(page.getByRole("combobox", { name: "签名服务" })).toBeFocused()
  await page.getByRole("button", { name: "取消", exact: true }).click()

  await page.getByRole("link", { name: "在线测试", exact: true }).click()
  await page.getByRole("combobox", { name: "API 接口" }).press("ArrowDown")
  await page.getByRole("option", { name: "Responses", exact: true }).press("End")
  await page.keyboard.press("Enter")
  await expect(page.getByRole("combobox", { name: "API 接口" })).toHaveText("Responses")
  await page.getByRole("combobox", { name: "模型", exact: true }).click()
  await page.getByRole("combobox", { name: "搜索模型", exact: true }).fill("custom-model-id")
  await page.getByRole("combobox", { name: "搜索模型", exact: true }).press("Enter")
  await expect(page.getByRole("combobox", { name: "模型", exact: true })).toHaveText("custom-model-id")
  await expect(page.getByRole("combobox", { name: "模型", exact: true })).toBeFocused()
  expect(errors).toEqual([])
})
