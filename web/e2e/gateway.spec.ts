import { expect, test } from "@playwright/test"

test("admin config, key lifecycle, both streaming APIs, logs, and responsive UI", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  await page.goto("/")
  await expect(page.getByRole("heading", { name: "登录管理控制台" })).toBeVisible()
  await page.screenshot({ path: "../test-results/login-desktop.png", fullPage: true })
  await page.getByLabel("管理员令牌").fill("e2e-admin-token-only-for-local-tests")
  await page.getByRole("button", { name: "进入控制台" }).click()
  await expect(page.getByRole("heading", { name: "网关总览", exact: true })).toBeVisible()
  await page.screenshot({ path: "../test-results/overview-empty.png", fullPage: true })
  await page.getByRole("link", { name: "添加上游", exact: true }).first().click()
  await page.getByRole("button", { name: "添加上游", exact: true }).click()
  await page.getByLabel("端点名称").fill("E2E · 模拟端点")
  await page.getByLabel("Base URL", { exact: true }).fill("http://127.0.0.1:18090/v1")
  await page.getByLabel("Bedrock API Key", { exact: true }).fill("mock-bedrock-key")
  await page.getByRole("button", { name: "保存上游" }).click()
  await expect(page.getByRole("heading", { name: "E2E · 模拟端点" })).toBeVisible()
  await page.getByRole("button", { name: "检测", exact: true }).click()
  await expect(page.getByRole("heading", { name: "连接检测成功" })).toBeVisible()
  await expect(page.getByText("mock-model", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "完成", exact: true }).click()
  await page.screenshot({ path: "../test-results/upstreams-desktop.png", fullPage: true })
  await page.getByRole("link", { name: "API 密钥", exact: true }).click()
  await page.getByRole("button", { name: "创建密钥", exact: true }).first().click()
  await page.getByLabel("密钥名称").fill("e2e-client")
  await page.getByRole("dialog").getByRole("button", { name: "创建密钥", exact: true }).click()
  await expect(page.getByRole("heading", { name: "API 密钥已创建" })).toBeVisible()
  const key = await page.locator(".created-key code").innerText()
  expect(key).toMatch(/^sk-mm-/)
  await page.getByRole("button", { name: "我已保存" }).click()
  const models = await page.request.get("/v1/models", { headers: { Authorization: `Bearer ${key}` } })
  expect(models.status()).toBe(200)
  expect((await models.json()).data[0].id).toBe("mock-model")
  await page.getByRole("link", { name: "在线测试", exact: true }).click()
  await expect(page.getByRole("combobox", { name: "模型", exact: true })).toContainText("mock-model")
  await page.getByLabel("输入提示词").fill("你好")
  await page.getByRole("button", { name: "发送请求" }).click()
  await expect(page.getByText("你好！Mantle Mask 的流式代理运行正常。", { exact: true })).toBeVisible()
  await expect(page.getByText("响应完成", { exact: true })).toBeVisible()
  await page.screenshot({ path: "../test-results/playground-desktop.png", fullPage: true })
  await page.getByRole("combobox", { name: "API 接口" }).click()
  await page.getByRole("option", { name: "Responses", exact: true }).click()
  await page.getByLabel("输入提示词").fill("测试 Responses")
  await page.getByRole("button", { name: "发送请求" }).click()
  await expect(page.getByText("你好！Mantle Mask 的流式代理运行正常。", { exact: true })).toBeVisible()
  await expect(page.getByText("20 tokens", { exact: true })).toBeVisible()
  await page.getByRole("link", { name: "请求日志", exact: true }).click()
  await expect(page.getByRole("cell", { name: "mock-model", exact: true }).first()).toBeVisible()
  await page.getByRole("link", { name: "网关设置", exact: true }).click()
  await page.getByLabel("请求总超时（秒）").fill("120")
  await page.getByRole("button", { name: "保存设置" }).click()
  await expect(page.getByText("网关设置已保存", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "关闭通知", exact: true }).click()
  await page.getByRole("link", { name: "总览", exact: true }).click()
  await page.screenshot({ path: "../test-results/overview-desktop.png", fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: "../test-results/overview-mobile.png", fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.setViewportSize({ width: 1440, height: 1060 })
  await page.getByRole("link", { name: "API 密钥", exact: true }).click()
  await page.getByRole("button", { name: "撤销", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "确认", exact: true }).click()
  await expect(page.getByText("e2e-client", { exact: true })).not.toBeVisible()
  const revoked = await page.request.get("/v1/models", { headers: { Authorization: `Bearer ${key}` } })
  expect(revoked.status()).toBe(401)
  await page.getByRole("button", { name: "退出登录" }).click()
  await expect(page.getByRole("heading", { name: "登录管理控制台" })).toBeVisible()
  expect(errors).toEqual([])
})
